import { fixReversedArabic } from './arabicFixer';

export interface InvoiceItem {
  id: string;
  seller: string;
  vatNumber: string;
  invoiceNumber: string;
  date: string;
  taxable: number | string;
  vat: number | string;
  total: number | string;
}

export interface ZatcaTags {
  [tag: number]: string;
}

export function base64ToBytes(b64: string): Uint8Array {
  const bin = atob(b64.trim());
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) {
    bytes[i] = bin.charCodeAt(i);
  }
  return bytes;
}

export function parseTLV(bytes: Uint8Array): ZatcaTags {
  const tags: ZatcaTags = {};
  let i = 0;
  const decoder = new TextDecoder('utf-8');
  while (i + 1 < bytes.length) {
    const tag = bytes[i];
    const len = bytes[i + 1];
    const start = i + 2;
    const end = start + len;
    if (end > bytes.length) break;
    tags[tag] = decoder.decode(bytes.slice(start, end));
    i = end;
  }
  return tags;
}

export function parseZatcaQR(text: string): { success: boolean; data?: Omit<InvoiceItem, 'id'>; error?: string } {
  try {
    const cleanText = text.trim();
    let tags: ZatcaTags | null = null;
    
    // First try standard base64 decoding
    try {
      tags = parseTLV(base64ToBytes(cleanText));
    } catch {
      tags = null;
    }

    if (!tags || Object.keys(tags).length === 0) {
      return {
        success: false,
        error: 'الرمز المقروء لا يطابق تنسيق فواتير زكاة وصدقة/ZATCA القياسي.',
      };
    }

    const rawSeller = tags[1] || '';
    // Fix inverted/reversed Arabic text frequently generated by older POS receipt systems
    const fixedSeller = fixReversedArabic(rawSeller);

    const totalNum = parseFloat(tags[4]);
    const vatNum = parseFloat(tags[5]);
    const taxable = (!isNaN(totalNum) && !isNaN(vatNum)) ? Math.round((totalNum - vatNum) * 100) / 100 : '';

    return {
      success: true,
      data: {
        seller: fixedSeller,
        vatNumber: tags[2] || '',
        invoiceNumber: '',
        date: tags[3] || '',
        taxable: taxable,
        vat: isNaN(vatNum) ? '' : vatNum,
        total: isNaN(totalNum) ? '' : totalNum,
      },
    };
  } catch (err: unknown) {
    const errorMsg = err instanceof Error ? err.message : 'خطأ غير متوقع أثناء معالجة الرمز';
    return {
      success: false,
      error: `تعذّر قراءة بيانات الفاتورة: ${errorMsg}`,
    };
  }
}
